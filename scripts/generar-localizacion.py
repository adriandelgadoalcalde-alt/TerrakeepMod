def anidar(pares):
    raiz = collections.OrderedDict()
    for clave, valor in pares:
        partes = clave.split(".")
        nodo = raiz
        for parte in partes[:-1]:
            nodo = nodo.setdefault(parte, collections.OrderedDict())
            assert isinstance(nodo, collections.OrderedDict), clave
        assert partes[-1] not in nodo, clave
        nodo[partes[-1]] = valor
    return raiz


def escribir(nodo, sangria, salida):
    tab = "\t" * sangria
    for clave, valor in nodo.items():
        if isinstance(valor, collections.OrderedDict):
            salida.append("%s%s: {" % (tab, clave))
            escribir(valor, sangria + 1, salida)
            salida.append("%s}" % tab)
        else:
            salida.append("%s%s: %s" % (tab, clave, json.dumps(valor, ensure_ascii=False)))


